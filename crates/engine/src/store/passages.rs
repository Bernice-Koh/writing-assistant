    /// The input of a published SHA-256 example and its digest. A captured passage holding it lands
    /// in gate and a synthetic one in bench.
    const FIXED_TEXT: &str = "The quick brown fox jumps over the lazy dog.";
    const FIXED_HASH: &str = "ef537f25c895bfa782526529a9b63d97aa631564d5d789c2b765448c8635fb6c";

    const KEY: &str = "document one";

    /// The number of passages each share test inserts, and how far a split's share may sit from
    /// its fraction, in percentage points.
    const N: usize = 10_000;
    const TOLERANCE_POINTS: f64 = 2.0;

    fn open(root: &TempRoot) -> Store {
        Store::open(root.path()).unwrap()
    }

    fn insert(
        store: &Store,
        kind: PassageKind,
        text: &str,
        document_key: Option<&str>,
    ) -> PassageId {
        store
            .insert_passage_blocking(kind, text, document_key)
            .unwrap()
    }

    fn split_of(store: &Store, id: PassageId) -> Split {
        store.passage_blocking(id).unwrap().split
    }

    /// The split `text` takes from its own content hash.
    fn own_split(text: &str, kind: PassageKind) -> Split {
        split_for(&sha256_hex(text.as_bytes()), kind)
    }

    /// The first text of the form `"{prefix} {n}"` whose own split for `kind` is not `split`.
    fn text_whose_own_split_is_not(split: Split, kind: PassageKind, prefix: &str) -> String {
        (0..)
            .map(|n| format!("{prefix} {n}"))
            .find(|text| own_split(text, kind) != split)
            .expect("some n gives another split")
    }

    fn row_count(store: &Store) -> i64 {
        store
            .request_blocking("count the passages", |connection| {
                connection.query_row("SELECT count(*) FROM passages", [], |row| row.get(0))
            })
            .unwrap()
    }

    fn counts_by_split(store: &Store) -> HashMap<Split, i64> {
        store
            .request_blocking("count the passages in each split", |connection| {
                connection
                    .prepare("SELECT split, count(*) FROM passages GROUP BY split")?
                    .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))?
                    .collect()
            })
            .unwrap()
    }

    /// Inserts `N` distinct passages of `kind` into a fresh store and holds each split's share
    /// within `TOLERANCE_POINTS` of its weight over the weights' total. Each test writes its
    /// weights out rather than reading the constants under test. A split absent from `weights`
    /// holds no passage.
    fn assert_shares(kind: PassageKind, weights: &[(Split, u32)]) {
        let root = TempRoot::new();
        let store = open(&root);
        // Durability is not under test. With a sync at every commit, the inserts take about 15
        // seconds on the development machine; in write-ahead mode, `NORMAL` syncs only at a
        // checkpoint.
        store
            .request_blocking("sync only at checkpoints", |connection| {
                connection.pragma_update(None, "synchronous", "NORMAL")
            })
            .unwrap();
        for n in 0..N {
            insert(&store, kind, &format!("distinct passage {n}"), None);
        }

        let counts = counts_by_split(&store);
        assert_eq!(counts.values().sum::<i64>(), N as i64);
        let total: u32 = weights.iter().map(|(_, weight)| weight).sum();
        for split in Split::ALL {
            let count = counts.get(&split).copied().unwrap_or(0);
            match weights.iter().find(|(weighted, _)| *weighted == split) {
                Some(&(_, weight)) => {
                    let expected = 100.0 * f64::from(weight) / f64::from(total);
                    let share = 100.0 * count as f64 / N as f64;
                    assert!(
                        (share - expected).abs() <= TOLERANCE_POINTS,
                        "{kind:?} passages in {split:?}: {count} of n = {N}, {share:.2}%, outside \
                         {expected:.2}% ± {TOLERANCE_POINTS} points"
                    );
                }
                None => assert_eq!(count, 0, "{kind:?} passages in {split:?}, of n = {N}"),
            }
        }
    }

