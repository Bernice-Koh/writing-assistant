//! The passages table: each piece of source text a rewrite, a bench item or a judgement item is
//! built on, stored once per kind with the split it was assigned at insert. The store computes a
//! passage's content hash and assigns its split, so a caller supplies only the kind, the text and,
//! where the capture layer gives one, a document key. Nothing writes a passage until Phase 4.
//!
//! A captured passage is the owner's own writing, so no error, log line or `Debug` rendering here
//! carries a passage's text: each names an operation, an id or a content hash instead.

use std::fmt;

use rusqlite::types::{FromSql, FromSqlError, FromSqlResult, ToSql, ToSqlOutput, ValueRef};
use rusqlite::{Connection, OptionalExtension, TransactionBehavior};

use super::error::StoreError;
use super::split::{split_for, Split};
use super::thread::Store;
use crate::hash::sha256_hex;

const INSERT_PASSAGE: &str = "insert a passage";
const READ_PASSAGE: &str = "read a passage";

/// Where a passage came from, which fixes the splits it can land in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum PassageKind {
    /// Generated by a model.
    Synthetic,
    /// The owner's own writing, captured from a document.
    Captured,
}

/// A passage's id in the store, assigned at its first insert and never given to another passage.
/// An `i64` because SQLite's integers are.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct PassageId(pub i64);

/// A passage as its row holds it.
#[derive(Clone, PartialEq, Eq)]
pub struct Passage {
    pub kind: PassageKind,
    pub text: String,
    /// The SHA-256 of the text, as lowercase hex.
    pub content_hash: String,
    pub split: Split,
    /// The durable key of the document the passage came from, where its insert was given one.
    pub document_key: Option<String>,
}

/// Shows the text's length in bytes in place of the text, since a `Debug` rendering ends up in log
/// lines and test failure messages. The content hash identifies the passage.
impl fmt::Debug for Passage {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("Passage")
            .field("kind", &self.kind)
            .field("text_bytes", &self.text.len())
            .field("content_hash", &self.content_hash)
            .field("split", &self.split)
            .field("document_key", &self.document_key)
            .finish()
    }
}

impl Store {
    /// Inserts a passage of `kind` holding `text`, with `document_key` where the capture layer gives
    /// one, and returns its id. The store computes the content hash and assigns the split; the
    /// caller supplies neither.
    ///
    /// Everything happens in one transaction. A stored passage of the same kind with the same
    /// content hash is this passage: its id returns and nothing is added, whatever document key
    /// either carries. Otherwise, with a document key, the split is that of the earliest stored
    /// passage of the same kind holding the key, so versions of one document never sit on both
    /// sides of a split boundary. With no key, or a key no stored passage of the kind holds, the
    /// split comes from the content hash and the kind alone.
    ///
    /// # Errors
    /// [`StoreError::Busy`] when another connection holds the write lock past the busy timeout,
    /// [`StoreError::Request`] for any other failure of the insert, and [`StoreError::ThreadGone`]
    /// when the store thread has stopped.
    pub async fn insert_passage(
        &self,
        kind: PassageKind,
        text: &str,
        document_key: Option<&str>,
    ) -> Result<PassageId, StoreError> {
        self.request(INSERT_PASSAGE, insert_work(kind, text, document_key))
            .await
    }

    /// [`insert_passage`](Self::insert_passage) for a synchronous caller, such as `wa`, which
    /// blocks on the reply.
    ///
    /// # Errors
    /// As [`insert_passage`](Self::insert_passage).
    ///
    /// # Panics
    /// When called from async code, which awaits [`insert_passage`](Self::insert_passage) instead.
    pub fn insert_passage_blocking(
        &self,
        kind: PassageKind,
        text: &str,
        document_key: Option<&str>,
    ) -> Result<PassageId, StoreError> {
        self.request_blocking(INSERT_PASSAGE, insert_work(kind, text, document_key))
    }

    /// The passage stored under `id`.
    ///
    /// # Errors
    /// [`StoreError::NoPassage`] when the store holds no passage under `id`, and otherwise as
    /// [`insert_passage`](Self::insert_passage).
    pub async fn passage(&self, id: PassageId) -> Result<Passage, StoreError> {
        self.request(READ_PASSAGE, move |connection| read(connection, id))
            .await?
            .ok_or(StoreError::NoPassage { id })
    }

    /// [`passage`](Self::passage) for a synchronous caller, such as `wa`, which blocks on the
    /// reply.
    ///
    /// # Errors
    /// As [`passage`](Self::passage).
    ///
    /// # Panics
    /// When called from async code, which awaits [`passage`](Self::passage) instead.
    pub fn passage_blocking(&self, id: PassageId) -> Result<Passage, StoreError> {
        self.request_blocking(READ_PASSAGE, move |connection| read(connection, id))?
            .ok_or(StoreError::NoPassage { id })
    }
}

/// The work of one insert, with the content hash computed before it reaches the store thread.
fn insert_work(
    kind: PassageKind,
    text: &str,
    document_key: Option<&str>,
) -> impl FnOnce(&mut Connection) -> rusqlite::Result<PassageId> + Send + 'static {
    let content_hash = sha256_hex(text.as_bytes());
    let text = text.to_owned();
    let document_key = document_key.map(str::to_owned);
    move |connection| {
        insert(
            connection,
            kind,
            &text,
            &content_hash,
            document_key.as_deref(),
        )
    }
}

/// Begins `IMMEDIATE`, so the lookups and the insert run under the write lock: another writer
/// waits inside the busy timeout rather than inserting the same passage, or the first passage of
/// the same document, between them.
fn insert(
    connection: &mut Connection,
    kind: PassageKind,
    text: &str,
    content_hash: &str,
    document_key: Option<&str>,
) -> rusqlite::Result<PassageId> {
    let transaction = connection.transaction_with_behavior(TransactionBehavior::Immediate)?;
    let stored: Option<i64> = transaction
        .query_row(
            "SELECT id FROM passages WHERE kind = ?1 AND content_hash = ?2",
            (kind, content_hash),
            |row| row.get(0),
        )
        .optional()?;
    if let Some(id) = stored {
        // Returning drops the transaction, which rolls it back, and it wrote nothing.
        return Ok(PassageId(id));
    }
    let grouped: Option<Split> = match document_key {
        Some(key) => transaction
            .query_row(
                "SELECT split FROM passages WHERE kind = ?1 AND document_key = ?2
                 ORDER BY id LIMIT 1",
                (kind, key),
                |row| row.get(0),
            )
            .optional()?,
        None => None,
    };
    let split = grouped.unwrap_or_else(|| split_for(content_hash, kind));
    transaction.execute(
        "INSERT INTO passages (kind, text, content_hash, split, document_key)
         VALUES (?1, ?2, ?3, ?4, ?5)",
        (kind, text, content_hash, split, document_key),
    )?;
    let id = transaction.last_insert_rowid();
    transaction.commit()?;
    Ok(PassageId(id))
}

fn read(connection: &Connection, id: PassageId) -> rusqlite::Result<Option<Passage>> {
    connection
        .query_row(
            "SELECT kind, text, content_hash, split, document_key FROM passages WHERE id = ?1",
            [id.0],
            |row| {
                Ok(Passage {
                    kind: row.get(0)?,
                    text: row.get(1)?,
                    content_hash: row.get(2)?,
                    split: row.get(3)?,
                    document_key: row.get(4)?,
                })
            },
        )
        .optional()
}

impl PassageKind {
    const ALL: [Self; 2] = [Self::Synthetic, Self::Captured];

    /// The kind as the `kind` column holds it, one of the names its CHECK constraint allows.
    fn column_value(self) -> &'static str {
        match self {
            Self::Synthetic => "synthetic",
            Self::Captured => "captured",
        }
    }
}

impl Split {
    const ALL: [Self; 5] = [
        Self::Train,
        Self::Monitor,
        Self::Bench,
        Self::Gate,
        Self::Sealed,
    ];

    /// The split as the `split` column holds it, one of the names its CHECK constraint allows.
    fn column_value(self) -> &'static str {
        match self {
            Self::Train => "train",
            Self::Monitor => "monitor",
            Self::Bench => "bench",
            Self::Gate => "gate",
            Self::Sealed => "sealed",
        }
    }
}

impl ToSql for PassageKind {
    fn to_sql(&self) -> rusqlite::Result<ToSqlOutput<'_>> {
        Ok(self.column_value().into())
    }
}

impl FromSql for PassageKind {
    fn column_result(value: ValueRef<'_>) -> FromSqlResult<Self> {
        from_column(value, &Self::ALL, Self::column_value)
    }
}

impl ToSql for Split {
    fn to_sql(&self) -> rusqlite::Result<ToSqlOutput<'_>> {
        Ok(self.column_value().into())
    }
}

impl FromSql for Split {
    fn column_result(value: ValueRef<'_>) -> FromSqlResult<Self> {
        from_column(value, &Self::ALL, Self::column_value)
    }
}

/// The one of `values` whose column value `value` holds. The CHECK constraints keep every stored
/// value among them, and the error leaves the value out, as every error of the module does.
pub(super) fn from_column<T: Copy>(
    value: ValueRef<'_>,
    values: &[T],
    column_value: fn(T) -> &'static str,
) -> FromSqlResult<T> {
    let stored = value.as_str()?;
    values
        .iter()
        .copied()
        .find(|candidate| column_value(*candidate) == stored)
        .ok_or_else(|| {
            FromSqlError::Other("a value outside the names the column's CHECK allows".into())
        })
}

